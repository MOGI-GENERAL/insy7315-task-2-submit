export type StringKey = keyof typeof en;

export type Dictionary = Record<StringKey, string>;

/** Afrikaans and isiXhosa download only when someone chooses them */
export function loadDictionary(language: Language): Promise<Dictionary> {
  if (language === 'af') return import('./af').then((m) => m.af);
  if (language === 'xh') return import('./xh').then((m) => m.xh);
  return Promise.resolve(en);
}

